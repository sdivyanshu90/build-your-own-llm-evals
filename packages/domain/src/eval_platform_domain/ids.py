"""Sortable UUIDv7 identifiers with monotonic process-local generation."""

from __future__ import annotations

import secrets
import threading
import time
import uuid
from collections.abc import Callable

_MAX_TIMESTAMP = (1 << 48) - 1
_MAX_RANDOM = (1 << 74) - 1


class UUID7Generator:
    """Generate RFC 9562 UUIDv7 values.

    Values generated by one instance are monotonic even when the wall clock moves
    backwards. Global uniqueness comes from 74 random bits; ordering across hosts
    remains approximate because clocks are not coordinated.
    """

    def __init__(
        self,
        clock_ms: Callable[[], int] | None = None,
        random_bits: Callable[[int], int] | None = None,
    ) -> None:
        self._clock_ms = clock_ms or (lambda: time.time_ns() // 1_000_000)
        self._random_bits = random_bits or secrets.randbits
        self._lock = threading.Lock()
        self._last_ms = -1
        self._random = 0

    def __call__(self) -> uuid.UUID:
        """Return the next UUIDv7 value."""

        with self._lock:
            timestamp = self._clock_ms()
            if timestamp < 0 or timestamp > _MAX_TIMESTAMP:
                raise ValueError("clock is outside the UUIDv7 48-bit timestamp range")
            if timestamp > self._last_ms:
                self._last_ms = timestamp
                self._random = self._random_bits(74) & _MAX_RANDOM
            else:
                timestamp = self._last_ms
                self._random += 1
                if self._random > _MAX_RANDOM:
                    raise RuntimeError("UUIDv7 random field exhausted within one millisecond")

            random_a = self._random >> 62
            random_b = self._random & ((1 << 62) - 1)
            value = (timestamp << 80) | (0x7 << 76) | (random_a << 64) | (0b10 << 62) | random_b
            return uuid.UUID(int=value)


_default_generator = UUID7Generator()


def new_uuid7() -> uuid.UUID:
    """Return a sortable UUIDv7 from the process-wide thread-safe generator."""

    return _default_generator()
